// Generates src/fonts/uiGlyphs.ts from reader/Src/UiGlyphs.c.
//
// UiGlyphs.c is the single source of truth for the built-in Chinese glyphs, so
// the Palm app and the web preview can never drift apart.
//
//   node scripts/gen-ui-glyphs.mjs

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '..');
const SOURCE = path.resolve(ROOT, '..', 'reader', 'Src', 'UiGlyphs.c');
const OUT = path.join(ROOT, 'src', 'fonts', 'uiGlyphs.ts');

const src = fs.readFileSync(SOURCE, 'utf8');

// One glyph per line, e.g.
//   { 0xC9CF, { 0x00, 0x10, ... } }, /* shang */
const lineRe = /\{\s*(0x[0-9A-Fa-f]{2}[0-9A-Fa-f]{2})\s*,\s*\{([^}]*)\}\s*\}/g;
const glyphs = [];
let match;
while ((match = lineRe.exec(src))) {
  const code = parseInt(match[1], 16);
  const rows = match[2]
    .split(',')
    .map((s) => s.trim())
    .filter(Boolean)
    .map((s) => parseInt(s, 16));
  if (rows.length !== 8) {
    throw new Error(`glyph 0x${code.toString(16)}: expected 8 rows, got ${rows.length}`);
  }
  if (glyphs.some((g) => g.code === code)) {
    throw new Error(`glyph 0x${code.toString(16)}: duplicate code`);
  }
  glyphs.push({ code, rows });
}

if (glyphs.length === 0) {
  throw new Error(`no glyphs parsed from ${SOURCE}`);
}

const rows = glyphs.map(
  (g) =>
    `  { code: 0x${g.code.toString(16).padStart(4, '0')}, rows: [${g.rows
      .map((b) => `0x${b.toString(16).padStart(2, '0')}`)
      .join(', ')}] },`,
);

const out = `// Generated by scripts/gen-ui-glyphs.mjs from reader/Src/UiGlyphs.c.
// Do not edit by hand: change the C table and rerun the generator.
//
// Built-in 8x8 Chinese glyphs, 8 rows each, MSB first, 1 = ink.

export const UI_GLYPH_WIDTH = 8;
export const UI_GLYPH_HEIGHT = 8;

export interface UiGlyphDef {
  /** GB2312 double-byte code, same as the glyph font PDB uses. */
  code: number;
  /** 8 rows, MSB first, 1 = ink. */
  rows: readonly number[];
}

export const UI_GLYPHS: readonly UiGlyphDef[] = [
${rows.join('\n')}
];

const byCode = new Map<number, readonly number[]>(
  UI_GLYPHS.map((g) => [g.code, g.rows]),
);

/** Glyph rows for a GB2312 code, or null when it is not built in. */
export function uiGlyphRows(code: number): readonly number[] | null {
  return byCode.get(code) ?? null;
}
`;

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, out);
console.log(`wrote ${OUT} (${glyphs.length} glyphs)`);
