// Generates src/fonts/hybrid6x8.ts from reader/Src/FontHybird6x8.h.
//
// The header stores 255 glyphs, 6x8, one byte per row, MSB-first, with the
// low two bits always clear. Only the ASCII range (0x20-0x7E) is used by the
// UI; the rest is kept for reference.
//
//   node scripts/gen-hybrid-font.mjs

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '..');
const HEADER = path.resolve(ROOT, '..', 'reader', 'Src', 'FontHybird6x8.h');
const OUT = path.join(ROOT, 'src', 'fonts', 'hybrid6x8.ts');

const src = fs.readFileSync(HEADER, 'utf8');

// One glyph per line: /* LABEL */ 0xNN, 0xNN, ... 8 bytes
const lineRe = /\/\*\s*(.+?)\s*\*\/\s*((?:0x[0-9A-Fa-f]{2}\s*,\s*){8})/g;
const glyphs = [];
let m;
while ((m = lineRe.exec(src))) {
  const label = m[1].trim();
  const bytes = m[2]
    .split(',')
    .map((s) => s.trim())
    .filter(Boolean)
    .map((s) => parseInt(s, 16));
  if (bytes.length !== 8) {
    throw new Error(`glyph ${label}: expected 8 bytes, got ${bytes.length}`);
  }
  for (const b of bytes) {
    if (b & 0x03) {
      throw new Error(`glyph ${label}: low two bits set in 0x${b.toString(16)}`);
    }
  }
  glyphs.push({ label, bytes });
}

if (glyphs.length !== 255) {
  throw new Error(`expected 255 glyphs, parsed ${glyphs.length}`);
}

const ascii = glyphs[0x20];
if (ascii.label !== 'SPACE') {
  throw new Error(`index 0x20 should be SPACE, got ${ascii.label}`);
}

const byteLines = [];
for (let i = 0; i < glyphs.length; i++) {
  byteLines.push(`  ${glyphs[i].bytes.map((b) => `0x${b.toString(16).padStart(2, '0')}`).join(', ')}, // 0x${i.toString(16).padStart(2, '0')} ${glyphs[i].label}`);
}

const labels = glyphs.map((g) => g.label);

const out = `// Generated by scripts/gen-hybrid-font.mjs. Do not edit.
//
// FontHybird 6x8: 255 glyphs, 6 pixels wide, 8 rows, MSB-first.
// Only 0x20-0x7E (ASCII) is used by the reader UI.
// Low two bits of every byte are always zero.

export const HYBRID_FONT_WIDTH = 6;
export const HYBRID_FONT_HEIGHT = 8;
export const HYBRID_FONT_COUNT = ${glyphs.length};

export const HYBRID_FONT_BYTES = new Uint8Array([
${byteLines.join('\n')}
]);

export const HYBRID_FONT_LABELS: readonly string[] = ${JSON.stringify(labels)};

/** First glyph index used by the UI. */
export const HYBRID_ASCII_FIRST = 0x20;
/** Last glyph index used by the UI. */
export const HYBRID_ASCII_LAST = 0x7e;

/** Row bytes for one glyph. */
export function hybridGlyph(index: number): Uint8Array {
  const base = index * HYBRID_FONT_HEIGHT;
  return HYBRID_FONT_BYTES.subarray(base, base + HYBRID_FONT_HEIGHT);
}
`;

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, out);
console.log(`wrote ${OUT} (${glyphs.length} glyphs)`);
